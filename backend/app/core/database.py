async def get_db() -> AsyncSession:
    """FastAPI dependency Ã¢â‚¬â€ yields an async DB session."""
    async with async_session() as session:
        try:
            yield session
            await session.commit()
        except Exception:
            await session.rollback()
            raise
        finally:
            await session.close()
